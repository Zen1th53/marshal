func TestSessionInventoryPrivateDatabaseOwnership(t *testing.T) {
	r, _ := openTestMemoryService(t)
	isolateSessionHistory(t)
	ctx := context.Background()
	for _, provider := range []string{"opencode", "antigravity"} {
		t.Run(provider, func(t *testing.T) {
			var path string
			if provider == "opencode" {
				path = filepath.Join(t.TempDir(), "opencode.db")
				t.Setenv("MARSHAL_OPENCODE_DB", path)
			} else {
				base := filepath.Join(os.Getenv("HOME"), ".gemini", "antigravity-cli")
				if err := os.MkdirAll(filepath.Join(base, "conversations"), 0700); err != nil {
					t.Fatal(err)
				}
				path = filepath.Join(base, "conversation_summaries.db")
				for _, id := range []string{"local-private", "foreign-private"} {
					if err := os.WriteFile(filepath.Join(base, "conversations", id+".db"), nil, 0600); err != nil {
						t.Fatal(err)
					}
				}
			}
			db, err := sql.Open("sqlite", path)
			if err != nil {
				t.Fatal(err)
			}
			if provider == "opencode" {
				if _, err := db.Exec(`CREATE TABLE session (id TEXT, directory TEXT, time_updated INTEGER)`); err != nil {
					t.Fatal(err)
				}
				for _, tc := range []struct{ id, dir string }{{"local-private", r.ProjectRoot()}, {"foreign-private", t.TempDir()}} {
					if _, err := db.Exec(`INSERT INTO session VALUES (?,?,?)`, tc.id, tc.dir, time.Now().UnixMilli()); err != nil {
						t.Fatal(err)
					}
				}
			} else {
				if _, err := db.Exec(`CREATE TABLE conversation_summaries (conversation_id TEXT, workspace_uris TEXT)`); err != nil {
					t.Fatal(err)
				}
				for _, tc := range []struct{ id, dir string }{{"local-private", r.ProjectRoot()}, {"foreign-private", t.TempDir()}} {
					raw, _ := json.Marshal([]string{"file://" + tc.dir})
					if _, err := db.Exec(`INSERT INTO conversation_summaries VALUES (?,?)`, tc.id, string(raw)); err != nil {
						t.Fatal(err)
					}
				}
			}
			if err := db.Close(); err != nil {
				t.Fatal(err)
			}
			inv, err := r.Sessions(ctx, provider)
			if err != nil || len(inv.Native) != 1 || inv.Native[0].SourceID != "local-private" || inv.Native[0].ProviderListed {
				t.Fatalf("private history: %+v %v", inv, err)
			}
		})
	}
}

