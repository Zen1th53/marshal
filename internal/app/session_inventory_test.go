func TestSessionInventoryBatchUsesNativeHomeAndProject(t *testing.T) {
	r, _ := openTestMemoryService(t)
	isolateSessionHistory(t)
	importInventoryConversation(t, r, "codex", "batch-source", time.Now().UTC())
	script := `#!/bin/sh
if [ "$1" = '--version' ]; then printf 'codex-cli 0.159.2\n'; exit 0; fi
printf 'HOME:<%s>\nDIR:<%s>\n' "$CODEX_HOME" "$PWD"
for arg do printf 'ARG:<%s>\n' "$arg"; done
`
	if err := os.WriteFile(filepath.Join(os.Getenv("PATH"), "codex"), []byte(script), 0700); err != nil {
		t.Fatal(err)
	}
	out, err := r.ExecuteNativeCodexConversation(context.Background(), "resume", "--last", []string{"quoted prompt"})
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{"HOME:<" + os.Getenv("CODEX_HOME") + ">", "DIR:<" + r.ProjectRoot() + ">", "ARG:<exec>", "ARG:<resume>", "ARG:<batch-source>", "ARG:<quoted prompt>"} {
		if !strings.Contains(out, want) {
			t.Fatalf("missing %s: %s", want, out)
		}
	}
	if _, err := r.ExecuteNativeCodexConversation(context.Background(), "resume", NativeConversationID("codex", t.TempDir(), "batch-source"), nil); err == nil || !strings.Contains(err.Error(), "another project") {
		t.Fatalf("batch project: %v", err)
	}
	if _, err := r.ExecuteNativeCodexConversation(context.Background(), "fork", "--last", nil); err == nil || !strings.Contains(err.Error(), "terminal-only") {
		t.Fatalf("batch dialect: %v", err)
	}
}
