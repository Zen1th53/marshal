func TestCodexModelValidationBeforeClaim(t *testing.T) {
	ctx := context.Background()
	repo := runtimeRepo(t)
	if _, err := Bootstrap(ctx, repo.Path()); err != nil {
		t.Fatal(err)
	}

	fake := newFakeCodexAdapter()
	runtime, err := OpenWithOptions(ctx, repo.Path(), Options{
		Adapters: map[string]adapter.Adapter{"codex": fake},
	})
	if err != nil {
		t.Fatal(err)
	}
	defer runtime.Close()

	agent, err := runtime.RegisterAgent(ctx, RegisterAgentRequest{Name: "dev-codex", Role: model.RoleDeveloper, ModelProvider: "codex"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := runtime.ImportTasks(ctx, []model.Task{
		{ID: "TASK-CODEX-VALIDATION", Title: "test model validation", Status: model.TaskReady, Risk: model.R1},
	}); err != nil {
		t.Fatal(err)
	}

	// 1. Unknown model must fail closed before claim
	_, err = runtime.Run(ctx, RunRequest{
		TaskID:           "TASK-CODEX-VALIDATION",
		AgentID:          agent.ID,
		Adapter:          "codex",
		Model:            "gpt-fake-nonexistent",
		ExpectedRevision: 0,
	})
	if err == nil || !errors.Is(err, model.ErrInvalid) {
		t.Fatalf("expected ErrInvalid for unknown model, got %v", err)
	}

	// Ensure no lease or session was created
	sessCount, err := runtime.store.Count(ctx, "sessions")
	if err != nil || sessCount != 0 {
		t.Fatalf("sessions count = %d, want 0 after rejected model validation", sessCount)
	}
	leaseCount, err := runtime.store.Count(ctx, "leases")
	if err != nil || leaseCount != 0 {
		t.Fatalf("lease count = %d, err = %v, want 0 after rejected model validation", leaseCount, err)
	}
	if fake.runs != 0 {
		t.Fatalf("fake adapter was run %d times, want 0", fake.runs)
	}

	// Adapter/provider binding is checked before the lease or provider launch;
	// a Claude (or arbitrary) principal cannot borrow Codex execution simply by
	// naming adapter="codex" through a local caller.
	wrongProvider, err := runtime.RegisterAgent(ctx, RegisterAgentRequest{Name: "dev-claude", Role: model.RoleDeveloper, ModelProvider: "claude"})
	if err != nil {
		t.Fatal(err)
	}
	_, err = runtime.Run(ctx, RunRequest{
		TaskID: "TASK-CODEX-VALIDATION", AgentID: wrongProvider.ID, Adapter: "codex", Model: "gpt-5.6-terra", ExpectedRevision: 0,
	})
	if !errors.Is(err, model.ErrInvalid) {
		t.Fatalf("wrong provider must be refused before claim: %v", err)
	}
	sessCount, err = runtime.store.Count(ctx, "sessions")
	if err != nil || sessCount != 0 || fake.runs != 0 {
		t.Fatalf("wrong-provider attempt must not create a session or launch Codex: sessions=%d runs=%d err=%v", sessCount, fake.runs, err)
	}

	// 2. Dangerous bypass flag in model name must fail closed with ErrPolicyDenied
	agent2, err := runtime.RegisterAgent(ctx, RegisterAgentRequest{Name: "dev-codex-2", Role: model.RoleDeveloper, ModelProvider: "codex"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := runtime.ImportTasks(ctx, []model.Task{
		{ID: "TASK-CODEX-DANGEROUS", Title: "test dangerous flag", Status: model.TaskReady, Risk: model.R1},
	}); err != nil {
		t.Fatal(err)
	}
	_, err = runtime.Run(ctx, RunRequest{
		TaskID:           "TASK-CODEX-DANGEROUS",
		AgentID:          agent2.ID,
		Adapter:          "codex",
		Model:            "--dangerously-bypass-approvals-and-sandbox",
		ExpectedRevision: 0,
	})
	if err == nil || !errors.Is(err, model.ErrPolicyDenied) {
		t.Fatalf("expected ErrPolicyDenied for dangerous flag, got %v", err)
	}
}

