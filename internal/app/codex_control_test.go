type fakeGovernedCodexAdapter struct {
	runs          int
	probes        int
	lastReq       adapter.Request
	allowedModels map[string]bool
}

func newFakeCodexAdapter() *fakeGovernedCodexAdapter {
	return &fakeGovernedCodexAdapter{
		allowedModels: map[string]bool{
			"gpt-5.6-terra": true,
			"gpt-6-astra":   true,
		},
	}
}

