	f.probes++
	return adapter.Probe{
		Name:      "codex",
		Available: true,
		Version:   "codex-cli 0.154.0",
		Capabilities: map[string]string{
			"run": "native", "sandbox": "native", "resume": "unsupported",
		},
	}, nil
