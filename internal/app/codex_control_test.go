func TestRuntimeProjectCodexSkillInstallIsDigestBoundAndAudited(t *testing.T) {
	ctx := context.Background()
	repo := runtimeRepo(t)
	if _, err := Bootstrap(ctx, repo.Path()); err != nil {
		t.Fatal(err)
	}
	source := filepath.Join(repo.Path(), ".agents", "skills", "project-skill")
	if err := os.MkdirAll(source, 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(source, "SKILL.md"), []byte("---\nname: project-skill\n---\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	runtime, err := Open(ctx, repo.Path())
	if err != nil {
		t.Fatal(err)
	}
	defer runtime.Close()
	digest, err := codex.PreviewProjectSkill(repo.Path(), "project-skill")
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("CODEX_HOME", t.TempDir())
	got, err := runtime.InstallProjectCodexSkill(ctx, "project-skill", digest)
	if err != nil || got != digest {
		t.Fatalf("install = %q, %v", got, err)
	}
	events, err := runtime.Events(ctx)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, event := range events {
		if event.Type == "CODEX_PROJECT_SKILL_INSTALLED" && event.Data["digest"] == digest {
			found = true
		}
	}
	if !found {
		t.Fatal("skill install audit event missing")
	}
}

func TestRuntimeProjectCodexSkillInstallCompensatesAuditFailure(t *testing.T) {
	ctx := context.Background()
	repo := runtimeRepo(t)
	if _, err := Bootstrap(ctx, repo.Path()); err != nil {
		t.Fatal(err)
	}
	source := filepath.Join(repo.Path(), ".agents", "skills", "audit-compensation")
	if err := os.MkdirAll(source, 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(source, "SKILL.md"), []byte("---\nname: audit-compensation\n---\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	runtime, err := Open(ctx, repo.Path())
	if err != nil {
		t.Fatal(err)
	}
	digest, err := codex.PreviewProjectSkill(repo.Path(), "audit-compensation")
	if err != nil {
		t.Fatal(err)
	}
	codexHome := t.TempDir()
	t.Setenv("CODEX_HOME", codexHome)
	// Closing the store makes the durable audit append fail after the adapter
	// has copied its private snapshot. The runtime must compensate that copy.
	if err := runtime.Close(); err != nil {
		t.Fatal(err)
	}
	if _, err := runtime.InstallProjectCodexSkill(ctx, "audit-compensation", digest); err == nil {
		t.Fatal("install succeeded despite unavailable audit store")
	}
	if _, err := os.Stat(filepath.Join(codexHome, "skills", "audit-compensation")); !os.IsNotExist(err) {
		t.Fatalf("unaudited skill was left installed: %v", err)
	}
}

func TestCodexRunEvidenceAndSessionBinding(t *testing.T) {
	ctx := context.Background()
	repo := runtimeRepo(t)
	if _, err := Bootstrap(ctx, repo.Path()); err != nil {
		t.Fatal(err)
	}

	fake := newFakeCodexAdapter()
	runtime, err := OpenWithOptions(ctx, repo.Path(), Options{
		Adapters: map[string]adapter.Adapter{"codex": fake},
	})
	if err != nil {
		t.Fatal(err)
	}
	defer runtime.Close()

	agent, err := runtime.RegisterAgent(ctx, RegisterAgentRequest{Name: "dev-codex-exec", Role: model.RoleDeveloper, ModelProvider: "codex"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := runtime.ImportTasks(ctx, []model.Task{
		{ID: "TASK-CODEX-RUN", Title: "governed codex run", Status: model.TaskReady, Risk: model.R1},
	}); err != nil {
		t.Fatal(err)
	}

	before, err := runtime.Task(ctx, "TASK-CODEX-RUN")
	if err != nil {
		t.Fatal(err)
	}

	// Run with explicit model
	res, err := runtime.Run(ctx, RunRequest{
		TaskID:           "TASK-CODEX-RUN",
		AgentID:          agent.ID,
		Adapter:          "codex",
		Model:            "gpt-5.6-terra",
		ExpectedRevision: 0,
	})
	if assertLegacyRunFixtureRefused(t, runtime, before, res, err) {
		if fake.probes != 0 || fake.runs != 0 {
			t.Fatal("refused legacy Run called the adapter", fake.probes, fake.runs)
		}
		return
	}
	if err != nil {
		t.Fatalf("Runtime.Run failed: %v", err)
	}

	if res.Status != "success" {
		t.Fatalf("res.Status = %s, want success", res.Status)
	}
	if res.SessionID != "thread_codex_governed_123" {
		t.Errorf("res.SessionID = %q, want thread_codex_governed_123", res.SessionID)
	}
	if res.Model != "gpt-5.6-terra" {
		t.Errorf("res.Model = %q, want gpt-5.6-terra", res.Model)
	}
	if res.RequestedModel != "gpt-5.6-terra" {
		t.Errorf("res.RequestedModel = %q, want gpt-5.6-terra", res.RequestedModel)
	}

	// Verify evidence nodes contain model and session_id
	cmdEv, err := runtime.Evidence(ctx, evidence.NodeID("EVIDENCE-RUN-"+res.RunID+"-COMMAND"))
	if err != nil {
		t.Fatalf("failed to retrieve COMMAND evidence: %v", err)
	}
	if cmdEv.Metadata["requested_model"] != "gpt-5.6-terra" {
		t.Errorf("cmd evidence requested_model = %q, want gpt-5.6-terra", cmdEv.Metadata["requested_model"])
	}
	if cmdEv.Metadata["effective_model"] != "gpt-5.6-terra" {
		t.Errorf("cmd evidence effective_model = %q, want gpt-5.6-terra", cmdEv.Metadata["effective_model"])
	}
	if cmdEv.Metadata["session_id"] != "thread_codex_governed_123" {
		t.Errorf("cmd evidence session_id = %q, want thread_codex_governed_123", cmdEv.Metadata["session_id"])
	}

	outEv, err := runtime.Evidence(ctx, evidence.NodeID("EVIDENCE-RUN-"+res.RunID+"-OUTPUT"))
	if err != nil {
		t.Fatalf("failed to retrieve OUTPUT evidence: %v", err)
	}
	if outEv.Metadata["effective_model"] != "gpt-5.6-terra" {
		t.Errorf("out evidence effective_model = %q, want gpt-5.6-terra", outEv.Metadata["effective_model"])
	}
	if outEv.Metadata["session_id"] != "thread_codex_governed_123" {
		t.Errorf("out evidence session_id = %q, want thread_codex_governed_123", outEv.Metadata["session_id"])
	}

	envEv, err := runtime.Evidence(ctx, evidence.NodeID("EVIDENCE-RUN-"+res.RunID+"-ENV"))
	if err != nil {
		t.Fatalf("failed to retrieve ENV evidence: %v", err)
	}
	if envEv.Metadata["effective_model"] != "gpt-5.6-terra" {
		t.Errorf("env evidence effective_model = %q, want gpt-5.6-terra", envEv.Metadata["effective_model"])
	}
	if envEv.Metadata["session_id"] != "thread_codex_governed_123" {
		t.Errorf("env evidence session_id = %q, want thread_codex_governed_123", envEv.Metadata["session_id"])
	}

	// 3. Duplicate submit rejection: running again with stale revision 0 must fail
	_, err = runtime.Run(ctx, RunRequest{
		TaskID:           "TASK-CODEX-RUN",
		AgentID:          agent.ID,
		Adapter:          "codex",
		Model:            "gpt-5.6-terra",
		ExpectedRevision: 0,
	})
	if err == nil {
		t.Fatal("expected duplicate submit with stale revision to fail, got nil")
	}
}
